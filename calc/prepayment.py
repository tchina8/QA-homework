"""Досрочное погашение: сокращение срока и уменьшение платежа.

Реализует раздел 3.6 спеки. Оба вида опираются на построитель графика
из `calc.annuity`; здесь задаётся только то, что именно фиксируется —
платёж или срок.

Порядок списания (раздел 3.6): досрочка вносится **вместе** с очередным платежом
и уменьшает остаток **после** разнесения этого платежа на проценты и тело.
Проценты месяца начисляются на остаток до досрочки. Если реализация спишет
досрочку раньше, числа эталонного примера 6.2 разойдутся уже на четвёртом месяце.
"""

from __future__ import annotations

from decimal import Decimal
from typing import Mapping, Sequence

from calc.annuity import ScheduleRow, build_schedule, total_interest

__all__ = [
    "schedule_with_term_reduction",
    "schedule_with_payment_reduction",
    "interest_saved",
    "term_reduction",
]


def schedule_with_term_reduction(
    principal: Decimal,
    annual_rate: Decimal,
    months: int,
    prepayments: Mapping[int, Decimal],
) -> list[ScheduleRow]:
    """Построить график при досрочке с сокращением срока.

    Вход: тело кредита `S`, годовая ставка `r`, исходный срок `n`,
    досрочки вида `{номер месяца: сумма}`.
    Выход: список `ScheduleRow`; строк может быть меньше `n`.

    Спека: раздел 3.6, строка «Сокращение срока». Платёж `A` остаётся неизменным,
    сокращается число оставшихся месяцев; график идёт до закрытия по условию (а)
    правила 3.4.

    Срок сокращается **на 0 или больше** месяцев — инвариант И-10 в нестрогой
    редакции. Копеечная досрочка срока не меняет вовсе: у последнего платежа
    и без неё есть запас, и досрочка уходит в его уменьшение (находка Н-3,
    раздел 4.2 спеки). На пороге сокращения последняя строка может оказаться
    равной `0.01` — это законный результат, а не дефект.

    Досрочка больше остатка обрезается до остатка (раздел 5); фактически
    применённая сумма видна в поле `prepayment` соответствующей строки.
    """
    return build_schedule(
        principal,
        annual_rate,
        months,
        prepayments=prepayments,
        keep_term=False,
        recalculate_payment=False,
    )


def schedule_with_payment_reduction(
    principal: Decimal,
    annual_rate: Decimal,
    months: int,
    prepayments: Mapping[int, Decimal],
) -> list[ScheduleRow]:
    """Построить график при досрочке с уменьшением платежа.

    Вход: тело кредита `S`, годовая ставка `r`, срок `n`,
    досрочки вида `{номер месяца: сумма}`.
    Выход: список `ScheduleRow` длиной ровно `n` строк (пока досрочка не закрыла долг).

    Спека: раздел 3.6, строка «Уменьшение платежа». Срок остаётся прежним,
    а платёж пересчитывается на остаток после досрочки и число оставшихся месяцев:
    `A' = money(annuity(B_k, i, n − k))`, и действует с месяца `k+1`.

    Поскольку срок здесь зафиксирован, платёж месяца `n` обязан добрать остаток
    по условию (б) правила 3.4. Без этого условия график оставляет хвост `0.01`
    и лишнюю строку на копейку — находка Н-1, зафиксированная в разделах 3.4 и 6.2
    спеки. Заодно это единственное место, где последний платёж может оказаться
    **больше** регулярного: в эталонном примере 6.2b это `77 174.76` против `77 174.75`.
    """
    return build_schedule(
        principal,
        annual_rate,
        months,
        prepayments=prepayments,
        keep_term=True,
        recalculate_payment=True,
    )


def interest_saved(
    base_schedule: Sequence[ScheduleRow], schedule_with_prepayment: Sequence[ScheduleRow]
) -> Decimal:
    """Посчитать экономию на процентах от досрочки.

    Вход: график без досрочек и график с досрочками по тому же кредиту.
    Выход: `Σ I_k` первого минус `Σ I_k` второго, `Decimal` с 2 знаками.

    Спека: сравнение видов в разделе 6.2 — сокращение срока экономит `9 165.35`,
    уменьшение платежа `5 066.32` на одних и тех же данных.

    Значение может быть равно `0.00`: копеечная досрочка не экономит ничего
    (находка Н-3, раздел 4.2). Отрицательным при корректных входных данных
    не бывает.
    """
    return total_interest(base_schedule) - total_interest(schedule_with_prepayment)


def term_reduction(
    base_schedule: Sequence[ScheduleRow], schedule_with_prepayment: Sequence[ScheduleRow]
) -> int:
    """Посчитать, на сколько месяцев сократился срок.

    Вход: график без досрочек и график с досрочками по тому же кредиту.
    Выход: разность числа строк, целое `≥ 0`.

    Спека: инвариант И-10 в нестрогой редакции и раздел 4.2. Ноль — штатный
    результат, а не признак ошибки: досрочка `0.01` на третьем месяце кредита
    из примера 6.1 оставляет все 12 строк на месте.
    """
    return len(base_schedule) - len(schedule_with_prepayment)
