"""Денежные величины: конструирование `Decimal` из строк и единственная точка округления.

Раздел 1.1 спеки («Контракт округления»): во всём пакете `calc/` округление денег
выполняется **только** функцией `money` из этого модуля. Ни один другой модуль пакета
не приводит числа к копейкам самостоятельно.

Раздел 1 спеки («Принятые решения»): деньги — `Decimal`, создаваемый только из строк.
Тип `float` не допускается ни на одном пути; попытка передать его отвергается `TypeError`,
а не молча теряет точность.
"""

from __future__ import annotations

from decimal import Decimal, ROUND_HALF_UP, localcontext

__all__ = [
    "CENT",
    "ZERO",
    "CALCULATION_PRECISION",
    "money",
    "decimal_from_str",
    "money_from_str",
    "calculation_context",
    "reject_float",
]

#: Шаг денежной сетки — копейка. Раздел 1 спеки: округление до 2 знаков.
CENT = Decimal("0.01")

#: Денежный ноль ровно с 2 знаками. Нужен для И-8 (все величины графика — 2 знака).
ZERO = Decimal("0.00")

#: Точность промежуточных вычислений.
#:
#: Раздел 1 спеки требует не округлять промежуточные множители: `i`, `(1 + i)^n`
#: и произведения остатка на ставку считаются «длинными». Значение 40 зафиксировано,
#: потому что именно с ним посчитаны эталонные примеры раздела 6 спеки; менять его
#: нельзя, не пересчитав таблицы 6.1–6.3.
CALCULATION_PRECISION = 40


def reject_float(value: object, name: str = "значение") -> None:
    """Отвергнуть `float` в денежном или ставочном расчёте.

    Вход: любое значение и его имя для сообщения об ошибке.
    Выход: `None`, если значение не `float`; иначе `TypeError`.

    Опирается на раздел 1 спеки: деньги создаются только из строк, никогда из `float`.
    Проверка сделана явной, чтобы дефект вылезал в точке передачи аргумента,
    а не расхождением в копейку через десять месяцев графика.
    """
    if isinstance(value, float):
        raise TypeError(
            f"{name}: получен float ({value!r}); "
            f"денежные величины и ставки создаются только из строк через Decimal"
        )


def money(value: Decimal) -> Decimal:
    """Округлить величину до копеек — единственная точка округления в пакете.

    Вход: `Decimal` произвольной точности.
    Выход: `Decimal` ровно с 2 знаками после запятой, режим `ROUND_HALF_UP`.

    Спека: раздел 1 (решение об округлении) и раздел 1.1 (контракт единственной функции).
    Инвариант И-8 опирается на то, что любая денежная величина графика прошла через неё.
    """
    reject_float(value, "money()")
    return value.quantize(CENT, rounding=ROUND_HALF_UP)


def decimal_from_str(text: str) -> Decimal:
    """Построить `Decimal` из строки без округления.

    Вход: строка вида `"0.12"`, `"9.5"`, `"1000000.00"`.
    Выход: точный `Decimal`, число знаков сохраняется как записано.

    Применяется к неденежным величинам — годовой ставке `r` и тарифу страхования `ρ`
    (раздел 2 спеки, оба не приводятся к копейкам).
    """
    if not isinstance(text, str):
        raise TypeError(
            f"decimal_from_str(): ожидается str, получен {type(text).__name__}; "
            f"раздел 1 спеки требует создавать Decimal только из строк"
        )
    return Decimal(text)


def money_from_str(text: str) -> Decimal:
    """Построить денежную величину из строки и привести её к копейкам.

    Вход: строка вида `"1000000.00"`, `"100000"`, `"0.01"`.
    Выход: `Decimal` ровно с 2 знаками, округление через `money`.

    Спека: раздел 1. Это штатный способ получить сумму кредита или досрочку
    во внешнем коде и в тестах.
    """
    return money(decimal_from_str(text))


def calculation_context():
    """Контекст промежуточных вычислений с фиксированной точностью.

    Вход: нет.
    Выход: менеджер контекста `decimal`, внутри которого точность равна
    `CALCULATION_PRECISION`.

    Спека: раздел 1 («промежуточные множители не округляются») и раздел 3.1,
    где `i = r / 12` явно помечена как неокругляемая. Контекст локальный: глобальные
    настройки `decimal` вызывающего кода не меняются.
    """
    return localcontext(prec=CALCULATION_PRECISION)
